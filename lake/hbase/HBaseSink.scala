// HBaseSink.scala - prepare the customer requests for HBase (Step 26).
//
// Run through lake/hbase/load_hbase.sh, which also creates the table and loads it:
//   bash lake/hbase/load_hbase.sh
//
// HBase is the serving store: one customer's latest requests, or one request, in
// milliseconds, without starting Spark or Hive. Table gss_requests:
//
//   row key   <sender handle>#<reversed time>#<msg id>
//             e.g. +971501234567#8288826232#M-2024-012345
//             All requests of one customer sit next to each other (a prefix scan finds them)
//             and, because the time is reversed (9999999999 - seconds since 1970), the newest
//             comes first. The msg id keeps two requests sent in the same second apart.
//   family r  the request: request_key, thread_id, channel, sent_at (UTC), origin_iata,
//             dest_iata, cargo_type, weight_kg, ready_date, special_handling, confidence,
//             missing_fields, status (complete / needs_info), attachments
//   family m  lineage: _src_file, _run_id, _batch_id
//
// The Spark and HBase versions on the VM have no common connector, and HBase client jars
// on Spark's classpath clash with Spark's own libraries. So this job writes the rows as a
// tab-separated file (/lake/tmp/hbase_requests) and HBase's own bulk loader, ImportTsv,
// puts them into the table. It also writes, in lake/hbase/:
//   importtsv_columns.txt   the column list for ImportTsv, in the same order as the file
//   demo_queries.hbase      HBase shell lookups with real keys from this load
//
// Spark 3.0.3, Scala 2.12, run with spark-shell -i (no sbt). One object = one unit for the REPL.

import org.apache.spark.sql.{functions => F}
import org.apache.spark.sql.expressions.Window

object HBaseSink {
  val hdfs = sys.env.getOrElse("GSS_HDFS", "hdfs://localhost:8020")
  val project = sys.env.getOrElse("GSS_PROJECT", sys.props("user.dir"))
  val outPath = hdfs + "/lake/tmp/hbase_requests"
  val table = "gss_requests"
  val rFields = Seq("request_key", "thread_id", "channel", "sent_at", "origin_iata", "dest_iata", "cargo_type",
                    "weight_kg", "ready_date", "special_handling", "confidence", "missing_fields", "status", "attachments")
  val mFields = Seq("_src_file", "_run_id", "_batch_id")

  def write(file: String, text: String): Unit = {
    val w = new java.io.PrintWriter(file, "UTF-8")
    try w.write(text) finally w.close()
  }

  def run(): Int = {
    spark.sparkContext.setLogLevel("WARN")
    val raw = spark.read.parquet(hdfs + "/lake/curated/request")
    // the stream writes at least once: keep the latest copy of each request
    val latest = Window.partitionBy("request_key").orderBy(F.col("_processed_at").desc)
    val req = raw.withColumn("_n", F.row_number().over(latest)).filter(F.col("_n") === 1).drop("_n")
      .withColumn("sent_at", F.date_format(F.col("sent_at"), "yyyy-MM-dd HH:mm:ss"))
      .withColumn("status", F.when(F.col("missing_fields").isNull, "complete").otherwise("needs_info"))
      .withColumn("row_key", F.concat_ws("#", F.coalesce(F.col("sender_handle"), F.lit("unknown")),
        F.lpad((F.lit(9999999999L) - F.unix_timestamp(F.col("sent_at"))).cast("string"), 10, "0"),
        F.col("request_key")))
      .persist()
    // every value as text, nulls as "", no tabs or line breaks inside a value
    val cols = ("row_key" +: (rFields ++ mFields)).map { c =>
      F.regexp_replace(F.coalesce(F.col(c).cast("string"), F.lit("")), "[\\t\\r\\n]", " ")
    }
    req.select(F.concat_ws("\t", cols: _*).as("line")).coalesce(1).write.mode("overwrite").text(outPath)

    val n = req.count()
    val dupes = raw.count() - n
    val columns = ("HBASE_ROW_KEY" +: rFields.map("r:" + _)) ++ mFields.map("m:" + _)
    write(project + "/lake/hbase/importtsv_columns.txt", columns.mkString(",") + "\n")

    // demo lookups with real keys: the busiest customer, one request, one that needs info
    val top = req.groupBy("sender_handle").count().orderBy(F.col("count").desc, F.col("sender_handle")).first()
    val handle = top.getString(0)
    val oneKey = req.filter(F.col("sender_handle") === handle).orderBy(F.col("row_key")).select("row_key").first().getString(0)
    val needs = req.filter(F.col("status") === "needs_info").orderBy("row_key").select("row_key").first().getString(0)
    val demo =
      s"""# HBase shell lookups, generated by lake/hbase/HBaseSink.scala with keys from this load.
         |#   hbase shell lake/hbase/demo_queries.hbase
         |
         |# 1. the latest 3 requests of the busiest customer ($handle, ${top.getLong(1)} requests): a prefix scan
         |scan '$table', {ROWPREFIXFILTER => '$handle#', LIMIT => 3, COLUMNS => ['r:sent_at', 'r:origin_iata', 'r:dest_iata', 'r:cargo_type', 'r:weight_kg', 'r:status']}
         |
         |# 2. one request by its full key: a single get
         |get '$table', '$oneKey'
         |
         |# 3. a request that still needs information from the customer
         |get '$table', '$needs', {COLUMNS => ['r:missing_fields', 'r:confidence', 'r:status']}
         |
         |# 4. all rows (expected $n)
         |count '$table', INTERVAL => 5000
         |exit
         |""".stripMargin
    write(project + "/lake/hbase/demo_queries.hbase", demo)

    println(s"Requests in curated/request: ${n + dupes} rows, $n distinct ($dupes duplicate copies dropped)")
    println(s"Wrote $n lines to $outPath")
    println(f"  needs_info ${req.filter(F.col("status") === "needs_info").count()}%6d   complete ${req.filter(F.col("status") === "complete").count()}%6d")
    println(s"Busiest customer: $handle (${top.getLong(1)} requests)")
    println("Example row key: " + oneKey)
    req.unpersist()
    0
  }
}

val gssRc = HBaseSink.run()
if (gssRc == 0) println("GSS_JOB_OK") else println("GSS_JOB_FAILED")
System.exit(gssRc)